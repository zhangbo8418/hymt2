/* 内嵌 MSL: 与 shaders/panel.comp、q4k.comp、q6k.comp 对齐。 */
#ifndef HYMT2_METAL_SHADERS_H
#define HYMT2_METAL_SHADERS_H

static const char HY_MSL_SRC[] =
"#include <metal_stdlib>\n"
"using namespace metal;\n"
"struct PC { uint rows, nb, nt, n_total, row0, shift, off, pad0; };\n"
"static inline uint hy_wbyte(device const uint *wq, uint base, uint i) {\n"
"  return (wq[base + (i >> 2)] >> (8u * (i & 3u))) & 255u;\n"
"}\n"
"static inline int hy_abyte(device const uint *act, uint base, uint i) {\n"
"  int v = as_type<int>(act[base + (i >> 2)]);\n"
"  uint s = 8u * (i & 3u);\n"
"  return (v << (24 - s)) >> 24;\n"
"}\n"
"static inline int hy_sbyte(uint b) { int v = int(b & 255u); return v >= 128 ? v - 256 : v; }\n"
"\n"
"kernel void hy_panel(\n"
"    device const uint *pk [[buffer(0)]],\n"
"    device const float *ps [[buffer(1)]],\n"
"    device const uint *act [[buffer(2)]],\n"
"    device float *outv [[buffer(3)]],\n"
"    constant PC &pc [[buffer(4)]],\n"
"    uint3 tid [[thread_position_in_threadgroup]],\n"
"    uint3 gid [[threadgroup_position_in_grid]])\n"
"{\n"
"  threadgroup float red[64];\n"
"  uint tix = tid.x;\n"
"  uint lr = tix >> 3, lane = tix & 7u;\n"
"  uint r = gid.x * 8u + lr, t = gid.y;\n"
"  (void)tid.y; (void)tid.z; (void)gid.z;\n"
"  float acc = 0.f;\n"
"  if (r < pc.rows) {\n"
"    for (uint b = lane; b < pc.nb; b += 8u) {\n"
"      uint wbase = (r * pc.nb + b) * 16u;\n"
"      uint abase = (t * pc.nb + b) * 144u;\n"
"      int enc = 0;\n"
"      for (uint j = 0u; j < 4u; j++) {\n"
"        for (uint wi = 0u; wi < 4u; wi++) {\n"
"          uint wv = pk[wbase + j * 4u + wi];\n"
"          for (uint l = 0u; l < 4u; l++) {\n"
"            int aw = as_type<int>(act[abase + l * 16u + j * 4u + wi]);\n"
"            uint wl = wv >> (2u * l);\n"
"            enc += int(wl & 3u) * ((aw << 24) >> 24);\n"
"            enc += int((wl >> 8) & 3u) * ((aw << 16) >> 24);\n"
"            enc += int((wl >> 16) & 3u) * ((aw << 8) >> 24);\n"
"            enc += int((wl >> 24) & 3u) * (aw >> 24);\n"
"          }\n"
"        }\n"
"      }\n"
"      float d = as_type<float>(act[abase + 64u]);\n"
"      int sm = as_type<int>(act[abase + 65u]);\n"
"      acc += ps[r * pc.nb + b] * d * float((enc << int(pc.shift)) - int(pc.off) * sm);\n"
"    }\n"
"  }\n"
"  red[tix] = acc;\n"
"  threadgroup_barrier(mem_flags::mem_threadgroup);\n"
"  if (lane == 0u && r < pc.rows) {\n"
"    float s = 0.f; for (uint i = 0u; i < 8u; i++) s += red[lr * 8u + i];\n"
"    outv[t * pc.n_total + pc.row0 + r] = s;\n"
"  }\n"
"}\n"
"\n"
"kernel void hy_q4k(\n"
"    device const uint *wq [[buffer(0)]],\n"
"    device const float *unused_s [[buffer(1)]],\n"
"    device const uint *act [[buffer(2)]],\n"
"    device float *outv [[buffer(3)]],\n"
"    constant PC &pc [[buffer(4)]],\n"
"    uint3 tid [[thread_position_in_threadgroup]],\n"
"    uint3 gid [[threadgroup_position_in_grid]])\n"
"{\n"
"  threadgroup float red[64]; (void)unused_s;\n"
"  uint tix = tid.x;\n"
"  uint lr = tix >> 3, lane = tix & 7u;\n"
"  uint r = gid.x * 8u + lr, t = gid.y;\n"
"  float acc = 0.f;\n"
"  if (r < pc.rows) {\n"
"    for (uint b = lane; b < pc.nb; b += 8u) {\n"
"      uint wb = (r * pc.nb + b) * 36u;\n"
"      uint ab = (t * pc.nb + b) * 144u;\n"
"      float2 dd = float2(as_type<half2>(wq[wb]));\n"
"      uint sc[8], mn[8];\n"
"      for (uint j = 0u; j < 8u; j++) {\n"
"        if (j < 4u) { sc[j] = hy_wbyte(wq, wb + 1u, j) & 63u; mn[j] = hy_wbyte(wq, wb + 1u, j + 4u) & 63u; }\n"
"        else {\n"
"          sc[j] = (hy_wbyte(wq, wb + 1u, j + 4u) & 15u) | ((hy_wbyte(wq, wb + 1u, j - 4u) >> 6) << 4);\n"
"          mn[j] = (hy_wbyte(wq, wb + 1u, j + 4u) >> 4) | ((hy_wbyte(wq, wb + 1u, j) >> 6) << 4);\n"
"        }\n"
"      }\n"
"      int sumi = 0;\n"
"      for (uint g = 0u; g < 4u; g++) {\n"
"        int s0 = 0, s1 = 0;\n"
"        for (uint l = 0u; l < 32u; l++) {\n"
"          uint q = hy_wbyte(wq, wb + 4u, 32u * g + l);\n"
"          s0 += int(q & 15u) * hy_abyte(act, ab + 80u, 64u * g + l);\n"
"          s1 += int(q >> 4) * hy_abyte(act, ab + 80u, 64u * g + 32u + l);\n"
"        }\n"
"        sumi += int(sc[2u * g]) * s0 + int(sc[2u * g + 1u]) * s1;\n"
"      }\n"
"      int summ = 0;\n"
"      for (uint j = 0u; j < 8u; j++) {\n"
"        uint w = act[ab + 66u + j];\n"
"        int lo = int(w & 0xffffu); if (lo >= 32768) lo -= 65536;\n"
"        int hi = int((w >> 16) & 0xffffu); if (hi >= 32768) hi -= 65536;\n"
"        summ += int(mn[j]) * (lo + hi);\n"
"      }\n"
"      float yd = as_type<float>(act[ab + 64u]);\n"
"      acc += yd * (dd.x * float(sumi) - dd.y * float(summ));\n"
"    }\n"
"  }\n"
"  red[tix] = acc;\n"
"  threadgroup_barrier(mem_flags::mem_threadgroup);\n"
"  if (lane == 0u && r < pc.rows) {\n"
"    float s = 0.f; for (uint i = 0u; i < 8u; i++) s += red[lr * 8u + i];\n"
"    outv[t * pc.n_total + pc.row0 + r] = s;\n"
"  }\n"
"}\n"
"\n"
"kernel void hy_q6k(\n"
"    device const uint *wq [[buffer(0)]],\n"
"    device const float *unused_s [[buffer(1)]],\n"
"    device const uint *act [[buffer(2)]],\n"
"    device float *outv [[buffer(3)]],\n"
"    constant PC &pc [[buffer(4)]],\n"
"    uint3 tid [[thread_position_in_threadgroup]],\n"
"    uint3 gid [[threadgroup_position_in_grid]])\n"
"{\n"
"  threadgroup float red[64]; (void)unused_s;\n"
"  uint tix = tid.x;\n"
"  uint lr = tix >> 3, lane = tix & 7u;\n"
"  uint r = gid.x * 8u + lr, t = gid.y;\n"
"  float acc = 0.f;\n"
"  if (r < pc.rows) {\n"
"    for (uint b = lane; b < pc.nb; b += 8u) {\n"
"      uint wb = (r * pc.nb + b) * 53u;\n"
"      uint ab = (t * pc.nb + b) * 144u;\n"
"      int isum = 0;\n"
"      for (uint n = 0u; n < 2u; n++) {\n"
"        for (uint l = 0u; l < 32u; l++) {\n"
"          uint qlo = hy_wbyte(wq, wb, 64u * n + l), qhi = hy_wbyte(wq, wb, 64u * n + l + 32u);\n"
"          uint qh = hy_wbyte(wq, wb + 32u, 32u * n + l);\n"
"          int q1 = int((qlo & 15u) | (((qh >> 0) & 3u) << 4)) - 32;\n"
"          int q2 = int((qhi & 15u) | (((qh >> 2) & 3u) << 4)) - 32;\n"
"          int q3 = int((qlo >> 4) | (((qh >> 4) & 3u) << 4)) - 32;\n"
"          int q4 = int((qhi >> 4) | (((qh >> 6) & 3u) << 4)) - 32;\n"
"          uint e = 128u * n + l;\n"
"          isum += hy_sbyte(hy_wbyte(wq, wb + 48u, e / 16u)) * q1 * hy_abyte(act, ab + 80u, e)\n"
"                + hy_sbyte(hy_wbyte(wq, wb + 48u, (e + 32u) / 16u)) * q2 * hy_abyte(act, ab + 80u, e + 32u)\n"
"                + hy_sbyte(hy_wbyte(wq, wb + 48u, (e + 64u) / 16u)) * q3 * hy_abyte(act, ab + 80u, e + 64u)\n"
"                + hy_sbyte(hy_wbyte(wq, wb + 48u, (e + 96u) / 16u)) * q4 * hy_abyte(act, ab + 80u, e + 96u);\n"
"        }\n"
"      }\n"
"      float d = float(as_type<half2>(wq[wb + 52u]).x);\n"
"      float yd = as_type<float>(act[ab + 64u]);\n"
"      acc += d * yd * float(isum);\n"
"    }\n"
"  }\n"
"  red[tix] = acc;\n"
"  threadgroup_barrier(mem_flags::mem_threadgroup);\n"
"  if (lane == 0u && r < pc.rows) {\n"
"    float s = 0.f; for (uint i = 0u; i < 8u; i++) s += red[lr * 8u + i];\n"
"    outv[t * pc.n_total + pc.row0 + r] = s;\n"
"  }\n"
"}\n";

#endif
