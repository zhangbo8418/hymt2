"kernel void hy_store_bf16(\n"
"    device const float *k [[buffer(0)]],\n"
"    device const float *v [[buffer(1)]],\n"
"    device ushort *kc [[buffer(2)]],\n"
"    device ushort *vc [[buffer(3)]],\n"
"    constant StorePC &pc [[buffer(4)]],\n"
"    uint2 gid [[thread_position_in_grid]])\n"
"{\n"
"  uint t = gid.y, d = gid.x;\n"
"  if (t >= pc.nt || d >= pc.kvdim) return;\n"
"  uint dst = (pc.pos0 + t) * pc.kvdim + d;\n"
"  uint bits_k = as_type<uint>(k[t * pc.kvdim + d]);\n"
"  uint bits_v = as_type<uint>(v[t * pc.kvdim + d]);\n"
"  kc[dst] = ushort((bits_k + 0x7fffu + ((bits_k >> 16) & 1u)) >> 16);\n"
"  vc[dst] = ushort((bits_v + 0x7fffu + ((bits_v >> 16) & 1u)) >> 16);\n"
"}\n"
"\n"
"static inline float bf16_f(ushort h) { return as_type<float>(uint(h) << 16); }\n"
"\n"
"kernel void hy_attn(\n"
"    device const float *q [[buffer(0)]],\n"
"    device const ushort *kc [[buffer(1)]],\n"
"    device const ushort *vc [[buffer(2)]],\n"
"    device float *ao [[buffer(3)]],\n"
"    constant AttnPC &pc [[buffer(4)]],\n"
"    uint lid [[thread_index_in_threadgroup]],\n"
"    uint2 tgpig [[threadgroup_position_in_grid]])\n"
"{\n"
"  uint h = tgpig.x, t = tgpig.y;\n"
"  if (h >= pc.heads || t >= pc.nt) return;\n"
"  uint group = pc.heads / max(pc.kv_heads, 1u);\n"
"  uint kvh = h / group;\n"
"  uint n = pc.pos0 + t + 1u;\n"
"  float scale = rsqrt(float(pc.hdim));\n"
"  device const float *qh = q + t * pc.qdim + h * pc.hdim;\n"
"  threadgroup float q_sh[256];\n"
"  threadgroup float red[64];\n"
"  /* 默认 ctx=2048：分数只算一遍 */\n"
"  threadgroup float scores[2048];\n"
"  for (uint d = lid; d < pc.hdim; d += 64u) q_sh[d] = qh[d];\n"
"  threadgroup_barrier(mem_flags::mem_threadgroup);\n"
"  uint ncap = min(n, 2048u);\n"
"  for (uint j = lid; j < ncap; j += 64u) {\n"
"    device const ushort *Krow = kc + j * pc.kvdim + kvh * pc.hdim;\n"
"    float s = 0.f;\n"
"    for (uint d = 0u; d < pc.hdim; d++) s += q_sh[d] * bf16_f(Krow[d]);\n"
"    scores[j] = s * scale;\n"
"  }\n"
"  threadgroup_barrier(mem_flags::mem_threadgroup);\n"
"  float mx = -1e30f;\n"
"  for (uint j = lid; j < ncap; j += 64u) if (scores[j] > mx) mx = scores[j];\n"
"  red[lid] = mx;\n"
"  threadgroup_barrier(mem_flags::mem_threadgroup);\n"
"  for (uint s = 32u; s > 0u; s >>= 1u) {\n"
"    if (lid < s) red[lid] = max(red[lid], red[lid + s]);\n"
"    threadgroup_barrier(mem_flags::mem_threadgroup);\n"
"  }\n"
"  mx = red[0];\n"
"  float sum = 0.f;\n"
"  for (uint j = lid; j < ncap; j += 64u) sum += exp(scores[j] - mx);\n"
"  red[lid] = sum;\n"
"  threadgroup_barrier(mem_flags::mem_threadgroup);\n"
"  for (uint s = 32u; s > 0u; s >>= 1u) {\n"
"    if (lid < s) red[lid] += red[lid + s];\n"
"    threadgroup_barrier(mem_flags::mem_threadgroup);\n"
"  }\n"
"  float inv = 1.f / red[0];\n"
"  float acc0 = 0.f, acc1 = 0.f, acc2 = 0.f, acc3 = 0.f;\n"
"  uint d0 = lid, d1 = lid + 64u, d2 = lid + 128u, d3 = lid + 192u;\n"
"  bool h1 = d1 < pc.hdim, h2 = d2 < pc.hdim, h3 = d3 < pc.hdim;\n"
"  for (uint j = 0u; j < ncap; j++) {\n"
"    float w = exp(scores[j] - mx) * inv;\n"
"    device const ushort *Vrow = vc + j * pc.kvdim + kvh * pc.hdim;\n"
"    acc0 += bf16_f(Vrow[d0]) * w;\n"
"    if (h1) acc1 += bf16_f(Vrow[d1]) * w;\n"
"    if (h2) acc2 += bf16_f(Vrow[d2]) * w;\n"
"    if (h3) acc3 += bf16_f(Vrow[d3]) * w;\n"
"  }\n"
"  device float *o = ao + t * pc.qdim + h * pc.hdim;\n"
"  o[d0] = acc0;\n"
"  if (h1) o[d1] = acc1;\n"
"  if (h2) o[d2] = acc2;\n"
"  if (h3) o[d3] = acc3;\n"
"}\n";

